// Timing + layout rules for 《同一根大阳线》 v4, checked against the very lists the picture draws from.
// Writes outputs-samecandle-v4/timing-report.md, outputs-samecandle-v4/layout-report.md and
// out/sc4-changes.json (frames where the picture is scheduled to change, for samecandle4-motion.py).
// Run: npm run sc4:timing   (exit 1 on any failure)
import fs from "node:fs";
import path from "node:path";
import { BEATS, CHAPTERS, EMPH, END_TEXT, IN_F, NAME, OUT_F, THREE_ITEMS, areaOf, barShown, labelBox, rowFocus, sceneOfChart, type Beat } from "../src/samecandle4/beats";
import { FPS, FRAMES, Lc, captions } from "../src/samecandle4/cue";
import { HERO, LANES, POSMAP } from "../src/samecandle4/data";
import { type Box, inside, inter, segHits, union } from "../src/samecandle4/geometry";
import { CUT, DISSOLVE, HOLD_CHART, IDS, POS_CHART, THREE_CARD, WHY, holdPost, rowChart, rowPost, sceneAt, volBars, volPost, volPrice } from "../src/samecandle4/layout";
import { CAPTION_BOX, arrowPts, axisBoxes, candleBoxes, headerBox, hlineSeg, holdShown, liveBeats, pathPts, rowBadgeBox, threeBoxes, volBarBoxes, volHeadBoxes } from "../src/samecandle4/shapes";
import TL from "../src/samecandle4/timeline.json";

const fails: string[] = [];
const out: string[] = [];
const lay: string[] = [];
const p = (s = "") => out.push(s);
const q = (s = "") => lay.push(s);
const sec = (f: number) => (f / FPS).toFixed(2);
const lines = Object.fromEntries(TL.lines.map((l) => [l.id, l]));
const hanzi = (s: string) => (s.match(/[一-鿿]/g) ?? []).length;
const r0 = (b: Box) => `${Math.round(b.x)},${Math.round(b.y)} ${Math.round(b.w)}×${Math.round(b.h)}`;

p("# 《同一根大阳线》v4 timing report");
p();
p(`Generated by \`npm run sc4:timing\` from \`src/samecandle4/beats.ts\`, \`layout.ts\` and \`shapes.ts\` (the lists the picture draws). 30 fps, ${FRAMES} frames = ${sec(FRAMES)} s. Voice = v1/v3 voice with 24 frames of silence added between the two sentences of w3 so "三件事" gets its own page (scripts/samecandle4-split.py).`);
p();

// ---------------------------------------------------------------- 1. cuts
p("## 1. Scene cuts");
p();
p("| cut | frame | previous line ends | wait | OK |");
p("|---|---|---|---|---|");
const CUTS: [string, number, string | null][] = [
  ["3D 开场 → 2D 三行 (4-frame dissolve)", CUT.rows - DISSOLVE, null],
  ["→ 为什么（单根K线）", CUT.why, "h3"],
  ["→ 三件事（新页面）", CUT.three, "w3a"],
  ["→ 01 位置", CUT.pos, "w3b"],
  ["→ 02 量能", CUT.vol, "p4"],
  ["→ 03 承接", CUT.hold, "v4"],
  ["→ 复盘（三行）", CUT.recap, "c5"],
  ["→ 结尾（同一图层变暗）", CUT.end, "r4"],
];
for (const [name, f, prev] of CUTS) {
  const wait = prev ? f - lines[prev].to : undefined;
  const ok = wait === undefined || wait >= 18;
  if (!ok) fails.push(`cut ${name}: ${wait}`);
  p(`| ${name} | ${f} (${sec(f)} s) | ${prev ? `${prev} @ ${lines[prev].to}` : "—"} | ${wait ?? "—"} | ${ok ? "✓" : "✗"} |`);
}
p();
p("3D exists only in frames 0–39; from frame 40 the film is fixed 2D layers with no camera and no shake.");
p();

// ---------------------------------------------------------------- 2. annotations
p("## 2. Annotations");
p();
p(`Rules: tied to a word → on the word (lead 0) or 4–8 frames before it; fully drawn (${IN_F} frames, stamp 5) it stays ≥ 24 frames, a card ≥ 36; only while its chart is on screen and after the chart has landed; every bar it points at is already drawn.`);
p();
p("| id | chart | kind | word (frame) | in | lead | holds | min | on screen | anchor | OK |");
p("|---|---|---|---|---|---|---|---|---|---|---|");
for (const b of BEATS) {
  const full = b.a + (b.inF ?? IN_F);
  const holds = Math.min(b.b, FRAMES) - OUT_F - full;
  const min = b.card ? 36 : 24;
  const kwF = b.kw ? Lc(b.kw[0], b.kw[1]) : undefined;
  const lead = kwF !== undefined ? kwF - b.a : undefined;
  const leadOk = lead === undefined || lead === 0 || (lead >= 4 && lead <= 8);
  const holdOk = holds >= min;
  const [s0, s1] = sceneOfChart(b.ch);
  const isRows = b.ch.startsWith("row");
  const onScreen = isRows ? (b.a >= CUT.rows && b.b <= CUT.why) || b.a >= CUT.recap : b.a > s0 && b.b <= s1;
  const anchorOk = (b.anchors ?? []).every((i) => barShown(b.ch, b.lane, i, b.a));
  [!leadOk && `lead ${lead}`, !holdOk && `holds ${holds} < ${min}`, !onScreen && "outside its chart's scene", !anchorOk && "points at a bar not drawn yet"].filter(Boolean).forEach((m) => fails.push(`${b.id}: ${m}`));
  const word = b.kw ? `${b.kw[0]}「${lines[b.kw[0]].text.slice(b.kw[1], b.kw[1] + 4)}」 ${kwF}` : "—";
  p(`| ${b.id} | ${b.ch} | ${b.kind} | ${word} | ${b.a} | ${lead ?? "—"} | ${holds} | ${min} | ${onScreen ? "✓" : "✗"} | ${anchorOk ? "✓" : "✗"} | ${leadOk && holdOk && onScreen && anchorOk ? "✓" : "✗"} |`);
}
p();
p("三件事 page (cards land with the cut; each row's title, icon and line appear on its word):");
p();
for (const t of THREE_ITEMS) {
  const lead = Lc(t.kw[0], t.kw[1]) - t.at;
  const holds = CUT.pos - OUT_F - (t.at + 9);
  const ok = holds >= 36 && (lead === 0 || (lead >= 4 && lead <= 8)) && t.at > CUT.three;
  if (!ok) fails.push(`three ${t.t}: lead ${lead} holds ${holds}`);
  p(`- ${t.n} ${t.t}: appears ${t.at} (lead ${lead}), holds ${holds} frames ${ok ? "✓" : "✗"}`);
}
p();

// ---------------------------------------------------------------- 3. focus
p("## 3. Focus");
p();
let worst = 0;
let worstAt = 0;
for (let f = 0; f < FRAMES; f++) {
  const n = BEATS.filter((b) => b.main && f >= b.a && f < b.b).length;
  if (n > worst) [worst, worstAt] = [n, f];
}
if (worst > 1) fails.push(`${worst} main explanations at frame ${worstAt}`);
p(`Most main explanation cards on screen at once: ${worst} ${worst <= 1 ? "✓" : `✗ (frame ${worstAt})`}.`);
p();

// ---------------------------------------------------------------- 4. emphasis
p("## 4. Emphasis on 「真正」 / 「最关键」");
p();
p("| word | line | voice reaches it | emphasis starts | lead | page dim | caption | chart |");
p("|---|---|---|---|---|---|---|---|");
for (const e of EMPH) {
  const L = lines[e.line];
  const idx = L.text.indexOf(e.word);
  const kwF = Lc(e.line, idx);
  const lead = kwF - e.at;
  const ok = lead >= 0 && lead <= 8 && idx >= 0;
  if (!ok) fails.push(`emphasis ${e.word}: lead ${lead}`);
  p(`| ${e.word} | ${e.line} | ${kwF} | ${e.at} | ${lead} ${ok ? "✓" : "✗"} | 10 % for ${e.len} frames (6-frame ramps) | gold underline + 1.12× | ${e.scene === "three" ? "three cards outlined, one 20-frame flash" : "hold chart outlined, one 20-frame flash"} |`);
}
p();
p("A soft low thump is placed on both moments in the mix. No camera shake anywhere (there is no camera after frame 40).");
p();

// ---------------------------------------------------------------- 5. phone text
p("## 5. Phone text");
p();
const texts: string[] = [];
BEATS.forEach((b) => b.label?.lines.forEach((l) => texts.push(l.t)));
THREE_ITEMS.forEach((t) => texts.push(t.t, t.d));
CHAPTERS.forEach((c) => texts.push(c.t, c.s));
Object.values(END_TEXT).forEach((t) => texts.push(t.t));
Object.values(NAME).forEach((t) => texts.push(t));
captions.forEach((c) => texts.push(c.text));
const long = texts.filter((t) => hanzi(t) > 12);
if (long.length) fails.push(`lines over 12 hanzi: ${long.join(" / ")}`);
const small = BEATS.flatMap((b) => b.label?.lines.filter((l) => l.size < 34).map((l) => `${b.id}:${l.t}`) ?? []);
if (small.length) fails.push(`text under 34 px: ${small.join(", ")}`);
p(`Every line ≤ 12 hanzi: ${long.length ? "✗ " + long.join(" / ") : "✓"} (${texts.length} lines). Every annotation line ≥ 34 px: ${small.length ? "✗ " + small.join(", ") : "✓"}. Labels 40–48 px, key numbers 60–110 px, captions 58 px; all horizontal.`);
p();

// ---------------------------------------------------------------- 6. layout: overlaps, areas, centring  (own report)
q("# 《同一根大阳线》v4 layout report: no overlaps, centred pages");
q();
q("Generated by `npm run sc4:timing` from the same geometry the renderer draws (every label is drawn in exactly the box checked here).");
q();
q("## 1. Labels never cover evidence");
q();
q("Every text box is tested on the first and last frame it is fully visible (and every 15 frames between) against: every drawn candle (body and wick), every volume bar, axis numbers, key price lines (open / close / half line / average), bands, arrows, paths, the chapter title, the caption bar and every other text box. A label must also stay inside its own chart's area. Minimum clearance: 2 px.");
q();
type Ob = { id: string; box?: Box; seg?: [{ x: number; y: number }, { x: number; y: number }] };
const visibleAt = (b: Beat, f: number) => f >= b.a + (b.inF ?? IN_F) && f < b.b - OUT_F;
const obstacles = (scene: string, f: number, self: Beat): Ob[] => {
  const o: Ob[] = [];
  const cand = (id: string, bs: Box[]) => bs.forEach((x, j) => o.push({ id: `${id}#${j}`, box: x }));
  if (scene === "rows" || scene === "recap")
    IDS.forEach((id, k) => {
      cand(`candle ${id}`, candleBoxes({ bars: LANES[id], c: rowChart(k), post: scene === "recap" ? 24 : rowPost(id, f) }));
      o.push({ id: `badge ${id}`, box: rowBadgeBox(k) });
    });
  if (scene === "why") cand("candle", candleBoxes({ bars: LANES.A, c: WHY, post: 0, from: HERO }));
  if (scene === "pos") cand("candle", candleBoxes({ bars: POSMAP, c: POS_CHART, post: 0, hero: POSMAP.length }));
  if (scene === "vol")
    IDS.forEach((id, k) => {
      cand(`candle ${id}`, candleBoxes({ bars: LANES[id], c: volPrice(k), post: volPost(id, f) }));
      cand(`vol bar ${id}`, volBarBoxes(id, f));
      volHeadBoxes(k, id).forEach((x, j) => o.push({ id: `col head ${id}${j}`, box: x }));
    });
  if (scene === "hold") {
    const s = holdShown(f);
    cand("candle A", candleBoxes({ bars: LANES.A, c: HOLD_CHART, post: s.A ? holdPost("A", f) : 0, from: HERO }));
    if (s.B) cand("candle B", candleBoxes({ bars: LANES.B, c: HOLD_CHART, post: holdPost("B", f), from: HERO + 1 }));
    if (s.C) cand("candle C", candleBoxes({ bars: LANES.C, c: HOLD_CHART, post: holdPost("C", f), from: HERO + 1 }));
    axisBoxes(HOLD_CHART).forEach((x) => o.push({ id: `axis ${x.v}`, box: x }));
  }
  const hb = headerBox(f);
  if (hb) o.push({ id: "chapter title", box: hb });
  o.push({ id: "caption bar", box: CAPTION_BOX });
  for (const b of liveBeats(scene)) {
    if (b === self || !(f >= b.a && f < b.b)) continue;
    if (b.label && visibleAt(b, f)) o.push({ id: `label ${b.id}`, box: labelBox(b.label) });
    if (b.kind === "hline") {
      const s = hlineSeg(b)!;
      o.push({ id: `line ${b.id}`, box: { x: s.x0, y: s.y - 3, w: s.x1 - s.x0, h: 6 } });
    }
    if (b.kind === "arrow") {
      const [a, z] = arrowPts(b);
      o.push({ id: `arrow ${b.id}`, seg: [a, z] });
    }
    if (b.kind === "path") {
      const pts = pathPts(b);
      pts.slice(1).forEach((z, j) => o.push({ id: `path ${b.id}`, seg: [pts[j], z] }));
    }
  }
  return o;
};
let overlapFails = 0;
let checks = 0;
q("| label | chart | box (x,y w×h) | inside own area | frames checked | clear | first conflict |");
q("|---|---|---|---|---|---|---|");
for (const b of BEATS) {
  if (!b.label || b.kind === "stamp") continue;
  const box = labelBox(b.label);
  const area = areaOf(b.ch);
  const inArea = inside(box, area);
  const f0 = b.a + (b.inF ?? IN_F);
  const f1 = Math.min(b.b, FRAMES) - OUT_F - 1;
  const frames = [f0, ...Array.from({ length: Math.floor((f1 - f0) / 15) }, (_, j) => f0 + 15 * (j + 1)), f1].filter((f) => f >= f0 && f <= f1);
  let conflict = "";
  for (const f of frames) {
    const scene = sceneAt(f);
    for (const ob of obstacles(scene, f, b)) {
      checks++;
      const hit = ob.box ? inter(box, ob.box, 2) : segHits(ob.seg![0], ob.seg![1], { x: box.x - 2, y: box.y - 2, w: box.w + 4, h: box.h + 4 });
      if (hit) {
        conflict = `${ob.id} @ ${f}`;
        break;
      }
    }
    if (conflict) break;
  }
  if (!inArea) fails.push(`${b.id}: label outside its chart area`);
  if (conflict) {
    overlapFails++;
    fails.push(`${b.id}: label overlaps ${conflict}`);
  }
  q(`| ${b.id} | ${b.ch} | ${r0(box)} | ${inArea ? "✓" : "✗"} | ${frames.length} | ${conflict ? "✗" : "✓"} | ${conflict || "—"} |`);
}
// stamp + 三件事 page
const stamp = BEATS.find((b) => b.kind === "stamp")!;
{
  const box = labelBox(stamp.label!);
  const f = stamp.a + 6;
  const hit = obstacles("hold", f, stamp).find((ob) => (ob.box ? inter(box, ob.box, 2) : segHits(ob.seg![0], ob.seg![1], box)));
  if (hit) fails.push(`holdTrap overlaps ${hit.id}`);
  q(`| holdTrap (stamp) | hold | ${r0(box)} | ${inside(box, areaOf("hold")) ? "✓" : "✗"} | 1 | ${hit ? "✗" : "✓"} | ${hit?.id ?? "—"} |`);
}
THREE_ITEMS.forEach((t, k) => {
  const B = threeBoxes(k);
  const parts: [string, Box][] = [["number", B.num], ["title", B.title], ["line", B.desc], ["icon", B.icon]];
  let bad = "";
  parts.forEach(([n, x], i) => {
    if (!inside(x, B.card)) bad ||= `${n} outside card`;
    parts.slice(i + 1).forEach(([m, y]) => inter(x, y, 2) && (bad ||= `${n} × ${m}`));
  });
  if (bad) fails.push(`三件事 ${t.n}: ${bad}`);
  q(`| 三件事 ${t.n} (number/title/line/icon) | three | ${r0(B.card)} | ✓ | — | ${bad ? "✗" : "✓"} | ${bad || "—"} |`);
});
q();
q(`${checks} box/obstacle tests, ${overlapFails} conflicts.`);
q();

// ---- centring
q("## 2. Every page is centred on x = 540");
q();
q("For each page, at the frame where it is fullest, the bounding box of its main visual parts (chart panels, badges, result columns, every visible label, the chapter title) is measured. Rule: its centre is within 40 px of 540, and the left and right margins are symmetric within 80 px.");
q();
q("| page | frame | content box x0–x1 | centre | offset | left / right margin | OK |");
q("|---|---|---|---|---|---|---|");
const panelBox = (c: { r: Box }) => ({ x: c.r.x - 14, y: c.r.y - 14, w: c.r.w + 28, h: c.r.h + 28 });
const pages: [string, string, number][] = [
  ["开场三行", "rows", CUT.why - 8],
  ["为什么", "why", CUT.three - 30],
  ["三件事", "three", CUT.pos - 8],
  ["01 位置", "pos", CUT.vol - 8],
  ["02 量能", "vol", CUT.hold - 8],
  ["03 承接", "hold", CUT.recap - 8],
  ["复盘三行", "recap", CUT.end - 8],
  ["结尾", "recap", FRAMES - 5],
];
for (const [name, scene, f] of pages) {
  const bs: Box[] = [];
  if (scene === "rows" || scene === "recap") IDS.forEach((_, k) => bs.push(panelBox(rowChart(k)), rowBadgeBox(k)));
  if (scene === "why") bs.push(panelBox(WHY));
  if (scene === "pos") bs.push(panelBox(POS_CHART));
  if (scene === "hold") bs.push(panelBox(HOLD_CHART));
  if (scene === "vol") IDS.forEach((id, k) => bs.push(panelBox(volPrice(k)), panelBox(volBars(k)), ...volHeadBoxes(k, id)));
  if (scene === "three") THREE_CARD.y.forEach((_, k) => bs.push(threeBoxes(k).card));
  liveBeats(scene).forEach((b) => b.label && f >= b.a && f < b.b && bs.push(labelBox(b.label)));
  const hb = headerBox(f);
  if (hb) bs.push(hb);
  const u = union(bs)!;
  const c = u.x + u.w / 2;
  const off = c - 540;
  const lm = u.x;
  const rm = 1080 - (u.x + u.w);
  const ok = Math.abs(off) <= 40 && Math.abs(lm - rm) <= 80;
  if (!ok) fails.push(`page ${name} off centre by ${off.toFixed(0)} px`);
  q(`| ${name} | ${f} | ${Math.round(u.x)}–${Math.round(u.x + u.w)} | ${c.toFixed(0)} | ${off >= 0 ? "+" : ""}${off.toFixed(0)} px | ${Math.round(lm)} / ${Math.round(rm)} | ${ok ? "✓" : "✗"} |`);
}
q();
q("Titles, captions, the end card and the 「示意图」 mark are centred text. No key text sits right of x = 950 (the platform button column) — see the phone preview.");
q();

// ---------------------------------------------------------------- 7. cadence + change schedule (for the motion check)
p("## 6. Something new while the voice speaks");
p();
const change = new Map<number, string[]>();
const mark = (f: number, why: string) => {
  if (f < 1 || f >= FRAMES) return;
  if (!change.has(f)) change.set(f, []);
  change.get(f)!.push(why);
};
const range = (a: number, b: number, why: string) => {
  for (let f = Math.max(1, a); f <= b; f++) mark(f, why);
};
const news = new Set<number>();
BEATS.forEach((b) => {
  news.add(b.a);
  range(b.a, b.a + (b.inF ?? IN_F), `${b.id} in`);
  range(b.b - OUT_F, b.b, `${b.id} out`);
  b.label?.lines.forEach((l) => {
    if (l.at !== undefined && l.at > b.a) {
      news.add(l.at);
      range(l.at, l.at + 8, `${b.id} line`);
    }
  });
});
THREE_ITEMS.forEach((t) => (news.add(t.at), range(t.at, t.at + 9, `三件事 ${t.n}`)));
CUTS.forEach(([n, f]) => (news.add(f), mark(f, `cut ${n}`)));
range(0, CUT.rows, "3D opening");
CHAPTERS.forEach((c) => (mark(c.a, "chapter title"), mark(c.b, "chapter title")));
Object.values(END_TEXT).forEach((t) => (news.add(t.a), range(t.a, t.a + 8, "end text")));
range(CUT.end, CUT.end + 4, "end dim");
range(END_TEXT.l3.a, END_TEXT.l3.a + 4, "answer lit");
EMPH.forEach((e) => (news.add(e.at), range(e.at, e.at + e.len + 7, `emphasis ${e.word}`)));
captions.forEach((c) => (mark(c.from, "caption"), mark(c.to, "caption")));
let prev = "";
for (let f = 0; f < FRAMES; f++) {
  const key = [sceneAt(f), ...IDS.map((id) => [rowPost(id, f), holdPost(id, f), volPost(id, f)].map((v) => v.toFixed(3)).join(","))].join("|");
  if (key !== prev) (mark(f, "bars growing"), news.add(f));
  prev = key;
}
BEATS.filter((b) => b.kind === "ratio").forEach((b) => mark(b.a, "column focus"));
let pf = "";
for (let f = CUT.recap; f < FRAMES; f++) {
  const v = IDS.map((id) => rowFocus(id, f)).join(",");
  if (v !== pf) mark(f, "row focus");
  pf = v;
}
const ev = [...news].sort((a, b) => a - b);
p("| line | text | from–to | longest stretch with nothing new (s) |");
p("|---|---|---|---|");
let longest = 0;
for (const l of TL.lines) {
  let last = l.from;
  let gap = 0;
  for (const e of ev.filter((e) => e > l.from && e <= l.to)) {
    gap = Math.max(gap, e - last);
    last = e;
  }
  gap = Math.max(gap, l.to - last);
  longest = Math.max(longest, gap);
  p(`| ${l.id} | ${l.text} | ${l.from}–${l.to} | ${sec(gap)} |`);
}
p();
const cadOk = longest <= 2.5 * FPS + 0.5;
if (!cadOk) fails.push(`longest still stretch while speaking ${sec(longest)} s`);
p(`Longest stretch of narration without new information: ${sec(longest)} s ${cadOk ? "✓" : "✗"}.`);
p();
p("Layout (overlaps, chart areas, centring): see `layout-report.md`.");
p();
const result = fails.length ? `## Result: ${fails.length} rule(s) failed\n\n${fails.map((f) => `- ${f}`).join("\n")}` : "## Result: all rules pass ✓";
p(result);
q(result);

const dir = path.resolve("../outputs-samecandle-v4");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "timing-report.md"), out.join("\n") + "\n", "utf8");
fs.writeFileSync(path.join(dir, "layout-report.md"), lay.join("\n") + "\n", "utf8");
fs.mkdirSync("out", { recursive: true });
fs.writeFileSync("out/sc4-changes.json", JSON.stringify({ frames: FRAMES, change: Object.fromEntries([...change].sort((a, b) => a[0] - b[0])) }));
console.log(fails.length ? `${fails.length} failed:\n` + fails.join("\n") : "all rules pass");
console.log(`longest still stretch while speaking: ${sec(longest)} s`);
process.exit(fails.length ? 1 : 0);
