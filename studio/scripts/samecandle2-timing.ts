// Timing report for 《同一根大阳线》 v2. Reads the very lists the HUD draws from (beats.ts) and the director's
// shot list, checks every timing rule, and writes outputs-samecandle-v2/timing-report.md.
// Run: npm run sc2:timing   (exits 1 if a rule fails)
import fs from "node:fs";
import path from "node:path";
import { BEATS, CHAPTERS, END_TEXT, IN_F, OUT_F, THREE_ITEMS, type Beat } from "../src/samecandle2/beats";
import { FPS, FRAMES, Lc } from "../src/samecandle2/cue";
import { T, TR, direct } from "../src/samecandle2/director";
import TL from "../src/samecandle2/timeline.json";

const fails: string[] = [];
const sec = (f: number) => (f / FPS).toFixed(2);
const out: string[] = [];
const p = (s = "") => out.push(s);

p("# 《同一根大阳线》v2 timing report");
p();
p(`Generated by \`npm run sc2:timing\` from \`src/samecandle2/beats.ts\` (the list the HUD draws) and \`director.ts\`. 30 fps, ${FRAMES} frames = ${sec(FRAMES)} s.`);
p();

// ---------------------------------------------------------------- 1. shots
p("## 1. Layout changes (\"切镜\")");
p();
p("Rule: a layout change starts ≥ 18 frames after the narration line before it ends; the move takes " + TR + " frames, then the frame is locked.");
p();
p("| shot | starts | settled | previous line ends | wait (frames) | OK |");
p("|---|---|---|---|---|---|");
const SHOTS: [string, number, string][] = [
  ["01 位置 · A 主图", T.solo, "w3"],
  ["01 位置 · B 主图", T.soloB, "p2"],
  ["01 位置 · C 主图", T.soloC, "p3"],
  ["02 量能 · 三列对齐", T.vol, "p4"],
  ["03 承接 · A 主图", T.holdA, "v4"],
  ["03 承接 · B 主图", T.holdB, "c3"],
  ["03 承接 · C 主图", T.holdC, "c4"],
  ["复盘 · 三行对齐", T.recap, "c5"],
  ["结尾", T.end, "r4"],
];
const lines = Object.fromEntries(TL.lines.map((l) => [l.id, l]));
for (const [name, at, prev] of SHOTS) {
  const wait = at - lines[prev].to;
  const ok = wait >= 18;
  if (!ok) fails.push(`shot ${name}: only ${wait} frames after ${prev}`);
  p(`| ${name} | ${at} (${sec(at)} s) | ${at + TR} | ${prev} @ ${lines[prev].to} | ${wait} | ${ok ? "✓" : "✗"} |`);
}
p();
p(`Camera: one move only, the opening pull-back from the macro (frames 14 → ${T.lock}); locked frontal for the rest of the film. No handheld, breathing, drift or orbit.`);
let shakeFrames = 0;
for (let f = 0; f < FRAMES; f++) if (direct(f).shake > 0) shakeFrames++;
const okShake = shakeFrames <= 6;
if (!okShake) fails.push(`shake lasts ${shakeFrames} frames`);
p(`Impact: one short shake on 「陷阱」, ${shakeFrames} frames (limit 4–6) ${okShake ? "✓" : "✗"}.`);
p();

// ---------------------------------------------------------------- 2. annotations
p("## 2. Annotations");
p();
p(`Rules: an annotation tied to a word starts 0–8 frames before the voice reaches it (default 6); fully drawn (${IN_F} frames, stamp 5) it stays ≥ 24 frames, a card ≥ 36; fade-out ${OUT_F} frames.`);
p();
p("| id | kind | layer | word (frame) | starts | lead | full | holds | min | OK |");
p("|---|---|---|---|---|---|---|---|---|---|");
const rowOf = (b: Beat) => {
  const full = b.a + (b.inF ?? IN_F);
  const holds = Math.min(b.b, FRAMES) - OUT_F - full;
  const min = b.card ? 36 : 24;
  const kwF = b.kw ? Lc(b.kw[0], b.kw[1]) : undefined;
  const lead = kwF !== undefined ? kwF - b.a : undefined;
  const leadOk = lead === undefined || (lead >= 0 && lead <= 8);
  const holdOk = holds >= min;
  if (!leadOk) fails.push(`${b.id}: lead ${lead}`);
  if (!holdOk) fails.push(`${b.id}: holds ${holds} < ${min}`);
  const word = b.kw ? `${b.kw[0]}「${lines[b.kw[0]].text.slice(b.kw[1], b.kw[1] + 4)}」 ${kwF}` : "— (follows the previous step)";
  p(`| ${b.id} | ${b.kind} | ${b.layer} | ${word} | ${b.a} | ${lead ?? "—"} | ${full} | ${holds} | ${min} | ${leadOk && holdOk ? "✓" : "✗"} |`);
};
BEATS.forEach(rowOf);
p();
p("Header cards (chapter titles, 「真正决定后面的」 list):");
p();
for (const c of CHAPTERS) {
  const holds = c.b - 8 - (c.a + 10);
  const ok = holds >= 36;
  if (!ok) fails.push(`chapter ${c.t}: holds ${holds}`);
  p(`- ${c.n ? c.n + " " : ""}${c.t}: ${c.a} → ${c.b}, holds ${holds} ${ok ? "✓" : "✗"}`);
}
for (const t of THREE_ITEMS) {
  const holds = T.solo - 8 - (t.at + 9);
  if (holds < 36) fails.push(`three item ${t.t}: ${holds}`);
  p(`- 三件事 ${t.n} ${t.t}: appears ${t.at}, holds ${holds} ${holds >= 36 ? "✓" : "✗"}`);
}
p();

// ---------------------------------------------------------------- 3. density: at most one main card + one aux layer
p("## 3. Focus: main cards on screen at once");
p();
let worst = 0;
const crowd: string[] = [];
for (let f = 0; f < FRAMES; f++) {
  const cards = BEATS.filter((b) => b.card && f >= b.a && f < b.b);
  worst = Math.max(worst, cards.length);
  if (cards.length > 1) crowd.push(`${f}: ${cards.map((b) => b.id).join(", ")}`);
}
if (worst > 1) fails.push(`more than one card at once (${crowd[0]})`);
p(`Most cards on screen at once: ${worst} ${worst <= 1 ? "✓" : "✗"}. One chart is the focus in every solo/hold shot (the other two are thumbnails at 55%); the volume shot dims the two columns not being discussed to 32%; the recap dims the rows not being read.`);
p();

// ---------------------------------------------------------------- 4. something new while the voice speaks
p("## 4. Picture changes while the voice speaks");
p();
p("Every beat start, layout change and post-bar reveal counts as new information. Listed: the longest stretch of each line with nothing new.");
p();
const events = new Set<number>();
BEATS.forEach((b) => events.add(b.a));
CHAPTERS.forEach((c) => events.add(c.a));
THREE_ITEMS.forEach((t) => events.add(t.at));
Object.values(END_TEXT).forEach((t) => events.add(t.a));
SHOTS.forEach(([, at]) => events.add(at));
let prevPost = "";
for (let f = 0; f < FRAMES; f++) {
  const d = direct(f);
  const key = ["A", "B", "C"].map((id) => Math.ceil((d.lanes as any)[id].post)).join(",");
  if (key !== prevPost) events.add(f);
  prevPost = key;
}
const ev = [...events].sort((a, b) => a - b);
p("| line | text | from–to | longest still stretch (s) |");
p("|---|---|---|---|");
let longest = 0;
for (const l of TL.lines) {
  let last = Math.max(...ev.filter((e) => e <= l.from).concat([0]));
  let gap = 0;
  for (const e of ev.filter((e) => e > l.from && e <= l.to)) {
    gap = Math.max(gap, e - last);
    last = e;
  }
  gap = Math.max(gap, l.to - last);
  longest = Math.max(longest, gap);
  p(`| ${l.id} | ${l.text} | ${l.from}–${l.to} | ${sec(gap)} |`);
}
p();
p(`Longest stretch of narration without a new element: ${sec(longest)} s.`);
p();
p(fails.length ? `## Result: ${fails.length} rule(s) failed\n\n${fails.map((f) => `- ${f}`).join("\n")}` : "## Result: all timing rules pass ✓");

const file = path.resolve("../outputs-samecandle-v2/timing-report.md");
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out.join("\n") + "\n", "utf8");
console.log(`wrote ${file}`);
console.log(fails.length ? `${fails.length} failed:\n` + fails.join("\n") : "all timing rules pass");
console.log(`longest still stretch while speaking: ${sec(longest)} s`);
process.exit(fails.length ? 1 : 0);
