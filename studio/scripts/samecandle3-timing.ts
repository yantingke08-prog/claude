// Timing + layout rules for 《同一根大阳线》 v3, checked against the very lists the picture draws from.
// Writes outputs-samecandle-v3/timing-report.md and out/sc3-changes.json (the frames where the picture is
// scheduled to change, used by samecandle3-motion.py). Run: npm run sc3:timing (exit 1 on any failure).
import fs from "node:fs";
import path from "node:path";
import { BEATS, CHAPTERS, END_TEXT, IN_F, NAME, OUT_F, THREE_ITEMS, barShown, rowFocus, sceneOfChart, type Beat } from "../src/samecandle3/beats";
import { FPS, FRAMES, Lc, captions } from "../src/samecandle3/cue";
import { CUT, DISSOLVE, holdPost, rowPost, sceneAt, volPost } from "../src/samecandle3/layout";
import TL from "../src/samecandle3/timeline.json";

const fails: string[] = [];
const out: string[] = [];
const p = (s = "") => out.push(s);
const sec = (f: number) => (f / FPS).toFixed(2);
const lines = Object.fromEntries(TL.lines.map((l) => [l.id, l]));
const hanzi = (s: string) => (s.match(/[一-鿿]/g) ?? []).length;

p("# 《同一根大阳线》v3 timing report");
p();
p(`Generated by \`npm run sc3:timing\` from \`src/samecandle3/beats.ts\` and \`layout.ts\` (the lists the picture draws). 30 fps, ${FRAMES} frames = ${sec(FRAMES)} s. Voice, script and timeline are v1's, unchanged.`);
p();

// ---------------------------------------------------------------- 1. cuts
p("## 1. Scene cuts");
p();
p("Each chapter replaces the whole chart layer in one hard cut (the only dissolve is the 4-frame 3D → 2D hand-off at the start). Rule: ≥ 18 frames after the narration line before it.");
p();
p("| cut | frame | previous line ends | wait | OK |");
p("|---|---|---|---|---|");
const CUTS: [string, number, string | null][] = [
  ["3D 开场 → 2D 三行 (4-frame dissolve)", CUT.rows - DISSOLVE, null],
  ["三行 → 为什么（单根K线）", CUT.why, "h3"],
  ["→ 01 位置（一张位置图）", CUT.pos, "w3"],
  ["→ 02 量能（三列成交量）", CUT.vol, "p4"],
  ["→ 03 承接（一张大图 + 路径）", CUT.hold, "v4"],
  ["→ 复盘（三行）", CUT.recap, "c5"],
  ["→ 结尾（三行变暗，同一图层）", CUT.end, "r4"],
];
for (const [name, f, prev] of CUTS) {
  const wait = prev ? f - lines[prev].to : undefined;
  const ok = wait === undefined || wait >= 18;
  if (!ok) fails.push(`cut ${name}: ${wait}`);
  p(`| ${name} | ${f} (${sec(f)} s) | ${prev ? `${prev} @ ${lines[prev].to}` : "—"} | ${wait ?? "—"} | ${ok ? "✓" : "✗"} |`);
}
p();
p("Camera: 3D exists only in frames 0–39 (macro hold 0–14, one pull-back 14–36, dissolve 36–40). From frame 40 the film is fixed 2D layers; there is no camera, no shake field, no breathing, drift, beam flicker, grain or chromatic aberration anywhere.");
p();

// ---------------------------------------------------------------- 2. annotations
p("## 2. Annotations");
p();
p(`Rules: tied to a word → appears on the word (lead 0) or 4–8 frames before it; fully drawn (${IN_F} frames, stamp 5) it stays ≥ 24 frames, a card ≥ 36; it may only exist while its chart is on screen, after the chart has landed, and every bar it points at must already be drawn.`);
p();
p("| id | chart | kind | word (frame) | in | lead | holds | min | chart on screen | anchor drawn | OK |");
p("|---|---|---|---|---|---|---|---|---|---|---|");
const rowOf = (b: Beat) => {
  const full = b.a + (b.inF ?? IN_F);
  const holds = Math.min(b.b, FRAMES) - OUT_F - full;
  const min = b.card ? 36 : 24;
  const kwF = b.kw ? Lc(b.kw[0], b.kw[1]) : undefined;
  const lead = kwF !== undefined ? kwF - b.a : undefined;
  const leadOk = lead === undefined || lead === 0 || (lead >= 4 && lead <= 8);
  const holdOk = holds >= min;
  const [s0, s1] = sceneOfChart(b.ch);
  const isRows = b.ch.startsWith("row");
  const inScene = isRows ? (b.a >= CUT.rows && b.b <= CUT.why) || b.a >= CUT.recap : b.a > s0 && b.b <= s1;
  const anchorOk = (b.anchors ?? []).every((i) => barShown(b.ch, b.lane, i, b.a));
  if (!leadOk) fails.push(`${b.id}: lead ${lead}`);
  if (!holdOk) fails.push(`${b.id}: holds ${holds} < ${min}`);
  if (!inScene) fails.push(`${b.id}: outside its chart's scene`);
  if (!anchorOk) fails.push(`${b.id}: points at a bar not drawn yet`);
  const word = b.kw ? `${b.kw[0]}「${lines[b.kw[0]].text.slice(b.kw[1], b.kw[1] + 4)}」 ${kwF}` : "—";
  p(`| ${b.id} | ${b.ch} | ${b.kind} | ${word} | ${b.a} | ${lead ?? "—"} | ${holds} | ${min} | ${inScene ? "✓" : "✗"} | ${anchorOk ? "✓" : "✗"} | ${leadOk && holdOk && inScene && anchorOk ? "✓" : "✗"} |`);
};
BEATS.forEach(rowOf);
p();
for (const t of THREE_ITEMS) {
  const holds = CUT.pos - OUT_F - (t.at + 9);
  if (holds < 36) fails.push(`three ${t.t}: ${holds}`);
  p(`- 三件事 ${t.n} ${t.t}: appears ${t.at}, holds ${holds} frames ${holds >= 36 ? "✓" : "✗"}`);
}
p();

// ---------------------------------------------------------------- 3. one main card
p("## 3. Focus");
p();
let worst = 0;
let worstAt = 0;
for (let f = 0; f < FRAMES; f++) {
  const n = BEATS.filter((b) => b.main && f >= b.a && f < b.b).length;
  if (n > worst) {
    worst = n;
    worstAt = f;
  }
}
if (worst > 1) fails.push(`${worst} main explanations at frame ${worstAt}`);
p(`Most main explanation cards on screen at once: ${worst} ${worst <= 1 ? "✓" : `✗ (frame ${worstAt})`}. Everything else on screen is one supporting layer (guide lines, rings, ratios, paths). A/B/C appear together only in the opening rows and the recap; every middle chapter is one chart layer of its own (位置: one map; 量能: three volume columns with their price thumbnails; 承接: one chart with the half line and the three paths).`);
p();

// ---------------------------------------------------------------- 4. phone text
p("## 4. Phone text");
p();
const texts: string[] = [];
BEATS.forEach((b) => {
  const x = b as unknown as Record<string, unknown>;
  ["text", "sub", "title", "value", "word"].forEach((k) => typeof x[k] === "string" && texts.push(x[k] as string));
  if (Array.isArray(x.lines)) (x.lines as { t: string }[]).forEach((l) => texts.push(l.t));
});
CHAPTERS.forEach((c) => texts.push(c.t, c.s));
Object.values(END_TEXT).forEach((t) => texts.push(t.t));
Object.values(NAME).forEach((t) => texts.push(t));
captions.forEach((c) => texts.push(c.text));
const long = texts.filter((t) => hanzi(t) > 12);
if (long.length) fails.push(`lines over 12 hanzi: ${long.join(" / ")}`);
p(`Every on-screen line ≤ 12 hanzi: ${long.length ? "✗ " + long.join(" / ") : "✓"} (${texts.length} lines checked, captions included).`);
p("Sizes (Stage.tsx): body ≥ 34 px, labels 40–48 px, key numbers 60–110 px, captions 58 px. All text is horizontal; no rotated labels. Key text stays left of x = 940 (the platform button column).");
p();

// ---------------------------------------------------------------- 5. cadence + the change schedule for the motion check
p("## 5. Something new while the voice speaks");
p();
const change = new Map<number, string[]>();
const mark = (f: number, why: string) => {
  if (f < 1 || f >= FRAMES) return;
  if (!change.has(f)) change.set(f, []);
  change.get(f)!.push(why);
};
const range = (a: number, b: number, why: string) => {
  for (let f = Math.max(1, a); f <= b; f++) mark(f, why);
};
const news = new Set<number>();
BEATS.forEach((b) => {
  news.add(b.a);
  range(b.a, b.a + (b.inF ?? IN_F), `${b.id} in`);
  range(b.b - OUT_F, b.b, `${b.id} out`);
  const x = b as unknown as { lines?: { at: number }[] };
  x.lines?.forEach((l) => {
    news.add(l.at);
    range(l.at, l.at + 8, `${b.id} line`);
  });
});
THREE_ITEMS.forEach((t) => {
  news.add(t.at);
  range(t.at, t.at + 9, "three item");
});
CUTS.forEach(([n, f]) => {
  news.add(f);
  mark(f, `cut ${n}`);
});
range(0, CUT.rows, "3D opening");
CHAPTERS.forEach((c) => (mark(c.a, "chapter title"), mark(c.b, "chapter title")));
Object.values(END_TEXT).forEach((t) => {
  news.add(t.a);
  range(t.a, t.a + 8, "end text");
});
range(CUT.end, CUT.end + 4, "end dim");
range(END_TEXT.l3.a, END_TEXT.l3.a + 4, "answer lit");
captions.forEach((c) => (mark(c.from, "caption"), mark(c.to, "caption")));
let prev = "";
for (let f = 0; f < FRAMES; f++) {
  const key = [sceneAt(f), ...(["A", "B", "C"] as const).map((id) => [rowPost(id, f), holdPost(id, f), volPost(id, f)].map((v) => v.toFixed(3)).join(","))].join("|");
  if (key !== prev) {
    mark(f, "bars growing");
    news.add(f);
  }
  prev = key;
}
// recap row focus and the volume column focus switch on their own frames
[...BEATS.filter((b) => b.kind === "ratio").map((b) => b.a)].forEach((f) => mark(f, "column focus"));
const recFocus = (f: number) => (["A", "B", "C"] as const).map((id) => rowFocus(id, f)).join(",");
let pf = "";
for (let f = CUT.recap; f < FRAMES; f++) {
  const v = recFocus(f);
  if (v !== pf) mark(f, "row focus");
  pf = v;
}
const ev = [...news].sort((a, b) => a - b);
p("| line | text | from–to | longest stretch with nothing new (s) |");
p("|---|---|---|---|");
let longest = 0;
for (const l of TL.lines) {
  let last = l.from; // count only while the voice is speaking
  let gap = 0;
  for (const e of ev.filter((e) => e > l.from && e <= l.to)) {
    gap = Math.max(gap, e - last);
    last = e;
  }
  gap = Math.max(gap, l.to - last);
  longest = Math.max(longest, gap);
  p(`| ${l.id} | ${l.text} | ${l.from}–${l.to} | ${sec(gap)} |`);
}
p();
const cadOk = longest <= 2.5 * FPS + 0.5;
if (!cadOk) fails.push(`longest still stretch while speaking ${sec(longest)} s`);
p(`Longest stretch of narration without new information: ${sec(longest)} s ${cadOk ? "✓" : "✗"} (target 1.5–2.5 s).`);
p();
p(fails.length ? `## Result: ${fails.length} rule(s) failed\n\n${fails.map((f) => `- ${f}`).join("\n")}` : "## Result: all timing rules pass ✓");

const file = path.resolve("../outputs-samecandle-v3/timing-report.md");
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out.join("\n") + "\n", "utf8");
fs.mkdirSync("out", { recursive: true });
fs.writeFileSync("out/sc3-changes.json", JSON.stringify({ frames: FRAMES, change: Object.fromEntries([...change].sort((a, b) => a[0] - b[0])) }));
console.log(`wrote ${file}`);
console.log(fails.length ? `${fails.length} failed:\n` + fails.join("\n") : "all timing rules pass");
console.log(`longest still stretch while speaking: ${sec(longest)} s`);
process.exit(fails.length ? 1 : 0);
